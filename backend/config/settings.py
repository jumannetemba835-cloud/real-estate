# The Neon pooler retains idle server connections per database, which blocks
# CREATE/DROP DATABASE during test setup. Tests therefore bypass the pooler
# (same credentials, direct host) and reuse the test database: always run
# them as `manage.py test --keepdb`. No secrets here, only a host rewrite.
if "test" in sys.argv:
    _direct_url = os.getenv("DATABASE_URL", "").replace("-pooler", "")
    if _direct_url:
        os.environ["DATABASE_URL"] = _direct_url


